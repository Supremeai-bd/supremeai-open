# backend/evolution/change_proposal.py
"""Safe Self-Evolution Change Proposal Lifecycle (P0 Self-Modification Governance).

Enforces:
Proposal -> Static/Security Scan -> Sandbox Benchmark -> Canary Gate -> Auto-Rollback
"""

from __future__ import annotations

import json
import os
import uuid
from collections.abc import Callable
from dataclasses import dataclass, field
from datetime import datetime
from enum import StrEnum
from pathlib import Path
from typing import Any

from core.logging_config import logger


class ProposalState(StrEnum):
    DRAFTED = "drafted"
    VALIDATED = "validated"
    SECURITY_CLEARED = "security_cleared"
    BENCHMARKED = "benchmarked"
    CANARY_ACTIVE = "canary_active"
    PROMOTED = "promoted"
    REJECTED = "rejected"
    ROLLED_BACK = "rolled_back"


class ChangeType(StrEnum):
    PROMPT_OPTIMIZATION = "prompt_optimization"
    PARAMETER_TUNING = "parameter_tuning"
    ROUTING_POLICY = "routing_policy"
    CODE_REFACTOR = "code_refactor"
    NEW_SKILL = "new_skill"


@dataclass
class ChangeProposal:
    """Formal, auditable change proposal generated by self-evolution agents."""

    title: str
    description: str
    change_type: ChangeType
    diff_content: dict[str, Any]
    target_module: str
    proposal_id: str = field(default_factory=lambda: f"prop_{uuid.uuid4().hex[:10]}")
    state: ProposalState = ProposalState.DRAFTED
    fitness_before: float = 0.0
    fitness_after: float | None = None
    security_scan_results: dict[str, Any] = field(default_factory=dict)
    benchmark_metrics: dict[str, Any] = field(default_factory=dict)
    canary_success_rate: float = 0.0
    rejection_reason: str | None = None
    created_at: datetime = field(default_factory=datetime.now)
    promoted_at: datetime | None = None
    # Sprint 6 (plan §19 Rollback Architecture): every autonomous change MUST
    # carry a rollback target — a description of the exact prior state to
    # restore (version/policy/config/artifact). Promotion is REFUSED without it.
    rollback_target: dict[str, Any] | None = None
    # Promotion is never autonomous: an authorized human must explicitly
    # approve the fully validated proposal before it can be promoted.
    human_approved: bool = False
    approved_by: str | None = None
    approved_at: datetime | None = None

    def advance_state(self, new_state: ProposalState) -> None:
        logger.info(
            f"🔄 Proposal [{self.proposal_id}] state: {self.state.value} -> {new_state.value}"
        )
        self.state = new_state
        if new_state == ProposalState.PROMOTED:
            self.promoted_at = datetime.now()

    def to_dict(self) -> dict[str, Any]:
        return {
            "proposal_id": self.proposal_id,
            "title": self.title,
            "description": self.description,
            "change_type": self.change_type.value,
            "diff_content": self.diff_content,
            "target_module": self.target_module,
            "state": self.state.value,
            "fitness_before": self.fitness_before,
            "fitness_after": self.fitness_after,
            "security_scan_results": self.security_scan_results,
            "benchmark_metrics": self.benchmark_metrics,
            "canary_success_rate": self.canary_success_rate,
            "rejection_reason": self.rejection_reason,
            "created_at": self.created_at.isoformat(),
            "promoted_at": self.promoted_at.isoformat() if self.promoted_at else None,
            "rollback_target": self.rollback_target,
            "human_approved": self.human_approved,
            "approved_by": self.approved_by,
            "approved_at": self.approved_at.isoformat() if self.approved_at else None,
        }


class ChangeProposalManager:
    """Governs the full lifecycle of AI self-modifications with persistent audit trail."""

    def __init__(
        self, storage_dir: str | None = None, config: dict[str, Any] | None = None
    ) -> None:
        self.config = config or {}
        self.storage_dir = Path(storage_dir or os.path.expanduser("~/.supremeai/proposals"))
        self.storage_dir.mkdir(parents=True, exist_ok=True)
        self.proposals: dict[str, ChangeProposal] = {}
        self.active_canaries: list[str] = []
        self._load_persisted_proposals()

    def _load_persisted_proposals(self) -> None:
        try:
            for filepath in self.storage_dir.glob("prop_*.json"):
                with open(filepath, encoding="utf-8") as fh:
                    data = json.load(fh)
                    proposal = ChangeProposal(
                        proposal_id=data["proposal_id"],
                        title=data["title"],
                        description=data["description"],
                        change_type=ChangeType(data["change_type"]),
                        diff_content=data["diff_content"],
                        target_module=data["target_module"],
                        state=ProposalState(data["state"]),
                        fitness_before=data.get("fitness_before", 0.0),
                        fitness_after=data.get("fitness_after"),
                        security_scan_results=data.get("security_scan_results", {}),
                        benchmark_metrics=data.get("benchmark_metrics", {}),
                        canary_success_rate=data.get("canary_success_rate", 0.0),
                        rejection_reason=data.get("rejection_reason"),
                        created_at=datetime.fromisoformat(data["created_at"]),
                        promoted_at=datetime.fromisoformat(data["promoted_at"])
                        if data.get("promoted_at")
                        else None,
                        rollback_target=data.get("rollback_target"),
                        human_approved=data.get("human_approved", False),
                        approved_by=data.get("approved_by"),
                        approved_at=datetime.fromisoformat(data["approved_at"])
                        if data.get("approved_at")
                        else None,
                    )
                    self.proposals[proposal.proposal_id] = proposal
        except Exception as exc:
            logger.warning(f"Could not load persisted change proposals: {exc}")

    def _persist_proposal(self, proposal: ChangeProposal) -> None:
        try:
            filepath = self.storage_dir / f"{proposal.proposal_id}.json"
            with open(filepath, "w", encoding="utf-8") as fh:
                json.dump(proposal.to_dict(), fh, indent=2)
        except Exception as exc:
            logger.warning(f"Could not persist proposal {proposal.proposal_id}: {exc}")

    def create_proposal(
        self,
        title: str,
        description: str,
        change_type: ChangeType,
        diff_content: dict[str, Any],
        target_module: str,
        current_fitness: float = 0.8,
    ) -> ChangeProposal:
        proposal = ChangeProposal(
            title=title,
            description=description,
            change_type=change_type,
            diff_content=diff_content,
            target_module=target_module,
            fitness_before=current_fitness,
        )

        # 🛡️ Governance Gate Pre-Check
        from core.security.governance_policy import get_governance_policy

        policy = get_governance_policy()
        is_allowed, reason = policy.validate_evolution_target(target_module)
        if not is_allowed:
            proposal.state = ProposalState.REJECTED
            proposal.rejection_reason = f"Governance policy violation: {reason}"
            self.proposals[proposal.proposal_id] = proposal
            self._persist_proposal(proposal)
            logger.critical(
                f"🚫 [GOVERNANCE GATE] Proposal [{proposal.proposal_id}] REJECTED: {reason}"
            )
            return proposal

        self.proposals[proposal.proposal_id] = proposal
        self._persist_proposal(proposal)
        logger.info(f"📝 Created new Change Proposal: {proposal.proposal_id} ({title})")
        return proposal

    def approve(self, proposal_id: str, approver: str) -> bool:
        """Record explicit human approval after reviewing the proposal."""
        proposal = self.proposals.get(proposal_id)
        if not proposal or not approver.strip():
            return False
        if proposal.state in {
            ProposalState.REJECTED,
            ProposalState.ROLLED_BACK,
            ProposalState.PROMOTED,
        }:
            return False
        proposal.human_approved = True
        proposal.approved_by = approver.strip()
        proposal.approved_at = datetime.now()
        self._persist_proposal(proposal)
        self._audit_run(proposal, run_type="APPROVAL", result=f"approved by {approver.strip()}")
        return True

    async def evaluate_and_promote(
        self,
        proposal_id: str,
        security_scanner_cb: Callable[[ChangeProposal], Any] | None = None,
        benchmarker_cb: Callable[[ChangeProposal], Any] | None = None,
        canary_runner_cb: Callable[[ChangeProposal], Any] | None = None,
    ) -> bool:
        """Run full gate: Static Scan -> Benchmark -> Canary Gate -> Promotion."""
        proposal = self.proposals.get(proposal_id)
        if not proposal:
            return False

        # 0. Governance Security Validation (Defense-in-depth)
        from core.security.governance_policy import get_governance_policy

        is_allowed, reason = get_governance_policy().validate_evolution_target(
            proposal.target_module
        )
        if not is_allowed:
            proposal.state = ProposalState.REJECTED
            proposal.rejection_reason = f"Governance policy violation: {reason}"
            self._persist_proposal(proposal)
            return False

        # 1. Static Validation
        if not proposal.diff_content or not proposal.target_module:
            proposal.state = ProposalState.REJECTED
            proposal.rejection_reason = "Empty diff or invalid target module"
            self._persist_proposal(proposal)
            return False
        proposal.advance_state(ProposalState.VALIDATED)

        # 2. Security Clearance
        if security_scanner_cb:
            sec_ok = await security_scanner_cb(proposal)
            if not sec_ok:
                proposal.advance_state(ProposalState.REJECTED)
                proposal.rejection_reason = "Security scan failed"
                self._persist_proposal(proposal)
                return False
        proposal.advance_state(ProposalState.SECURITY_CLEARED)

        # 3. Benchmark Verification (Audit Finding #5: Never assume artificial improvement)
        if benchmarker_cb is None:
            proposal.advance_state(ProposalState.REJECTED)
            proposal.rejection_reason = (
                "No benchmark runner provided; self-evolution requires objective verification"
            )
            self._persist_proposal(proposal)
            return False

        new_fitness = await benchmarker_cb(proposal)
        proposal.fitness_after = new_fitness
        if new_fitness < proposal.fitness_before:
            proposal.advance_state(ProposalState.REJECTED)
            proposal.rejection_reason = (
                f"Fitness regression: {new_fitness:.3f} < {proposal.fitness_before:.3f}"
            )
            self._persist_proposal(proposal)
            return False

        proposal.advance_state(ProposalState.BENCHMARKED)

        # 4. Rollback and human-approval gates (Sprint 6, plan §19: "No rollback target = no
        # autonomous promotion.") A promotion without a described, restorable
        # prior state is irreversible — therefore forbidden.
        if not proposal.rollback_target or not isinstance(proposal.rollback_target, dict):
            proposal.advance_state(ProposalState.REJECTED)
            proposal.rejection_reason = (
                "No rollback target — autonomous promotion refused (plan §19)"
            )
            self._persist_proposal(proposal)
            logger.critical(
                f"🚫 [ROLLBACK GATE] Proposal [{proposal_id}] REJECTED: no rollback target."
            )
            return False

        # 5. Canary Testing Gate. A callback and real observations are
        # mandatory; never promote based on a fabricated/default rate.
        if canary_runner_cb is None:
            proposal.advance_state(ProposalState.REJECTED)
            proposal.rejection_reason = "Canary runner required before promotion"
            self._persist_proposal(proposal)
            return False
        proposal.advance_state(ProposalState.CANARY_ACTIVE)
        canary_result = await canary_runner_cb(proposal)
        if not isinstance(canary_result, dict):
            canary_result = {}
        success_rate = canary_result.get("success_rate")
        observations = canary_result.get("observations", 0)
        if not isinstance(success_rate, (int, float)) or not 0 <= success_rate <= 1:
            proposal.advance_state(ProposalState.REJECTED)
            proposal.rejection_reason = "Canary result must include a success_rate in [0, 1]"
            self._persist_proposal(proposal)
            return False
        if not isinstance(observations, int) or observations < 1:
            proposal.advance_state(ProposalState.REJECTED)
            proposal.rejection_reason = "Canary result must include at least one observation"
            self._persist_proposal(proposal)
            return False
        proposal.canary_success_rate = float(success_rate)
        proposal.benchmark_metrics["canary"] = canary_result
        minimum_canary_rate = float(self.config.get("minimum_canary_success_rate", 0.99))
        if proposal.canary_success_rate < minimum_canary_rate:
            proposal.advance_state(ProposalState.REJECTED)
            proposal.rejection_reason = (
                f"Canary regression: {proposal.canary_success_rate:.3f} < {minimum_canary_rate:.3f}"
            )
            self._persist_proposal(proposal)
            return False

        if not proposal.human_approved or not proposal.approved_by:
            proposal.advance_state(ProposalState.REJECTED)
            proposal.rejection_reason = "Explicit human approval required before promotion"
            self._persist_proposal(proposal)
            return False

        # Sprint 6: audit trail — every lifecycle transition lands in the
        # durable improvement_runs store (best-effort; never blocks promotion).
        self._audit_run(proposal, run_type="PROMOTION", result="promoted")

        # 6. Final Promotion
        proposal.advance_state(ProposalState.PROMOTED)
        self._persist_proposal(proposal)
        logger.info(f"🎉 Change Proposal [{proposal_id}] successfully PROMOTED to production!")
        return True

    def _audit_run(self, proposal: ChangeProposal, *, run_type: str, result: str) -> None:
        """Best-effort durable audit row (improvement_runs) for a transition."""
        try:
            from database.supabase_client import db as supabase_db

            supabase_db.insert_improvement_run(
                {
                    "proposal_id": proposal.proposal_id,
                    "run_type": run_type,
                    "result": result,
                    "metrics": {
                        "fitness_before": proposal.fitness_before,
                        "fitness_after": proposal.fitness_after,
                    },
                    "notes": f"target={proposal.target_module} state={proposal.state.value}",
                }
            )
        except Exception as exc:  # audit is best-effort; promotion continues
            logger.debug(f"improvement_run audit skipped: {exc}")

    def rollback(self, proposal_id: str, reason: str) -> bool:
        proposal = self.proposals.get(proposal_id)
        if not proposal:
            return False
        proposal.advance_state(ProposalState.ROLLED_BACK)
        proposal.rejection_reason = f"Rolled back: {reason}"
        self._persist_proposal(proposal)
        self._audit_run(proposal, run_type="ROLLBACK", result=f"rolled back: {reason}")
        logger.warning(f"⚠️ Change Proposal [{proposal_id}] rolled back: {reason}")
        return True


# Global Singleton
_change_manager: ChangeProposalManager | None = None


def get_change_manager() -> ChangeProposalManager:
    global _change_manager
    if _change_manager is None:
        _change_manager = ChangeProposalManager()
    return _change_manager
