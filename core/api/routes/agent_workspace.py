import asyncio

from fastapi import APIRouter, Depends, WebSocket, WebSocketDisconnect
from pydantic import BaseModel

from api.dependencies import get_current_user_token
from core.knowledge_base import get_from_memory, save_to_memory
from core.logging_config import logger
from core.security.ws_auth import authenticate_websocket

# 🛡️ SECURITY FIX: এই router-এর কোনো HTTP endpoint-এই আগে কোনো authentication
# ছিল না — /agent/learn অন্য যেকোনো (unauthenticated) কলার একটা shared, global
# memory file (knowledge_base.py-এর MEMORY_FILE_PATH, prompt-string দিয়ে keyed,
# কোনো user/tenant scoping ছাড়া)-এ সরাসরি লিখতে পারত। এরপর /agent/execute একই
# prompt-এর জন্য সেই (potentially malicious) cached "solution code" যেকোনো
# ইউজারকে ফেরত দিত — অর্থাৎ একজন অননুমোদিত attacker পুরো সিস্টেমের সব ইউজারের
# জন্য একটা shared code-cache poison করতে পারত।
#
# NOTE: get_current_user_token() Request.state.user পড়ে, যেটা AuthMiddleware
# শুধু HTTP scope-এ সেট করে (websocket scope-এ না, দেখুন
# core/security/auth_middleware.py:167 `if scope["type"] != "http"`), তাই এই
# dependency router-level না বসিয়ে শুধু নিচের HTTP POST endpoint গুলোতে
# per-endpoint বসানো হলো — নাহলে /agent/terminal-stream websocket route-টা
# .accept()-এর আগেই সবসময় 401 দিয়ে ভেঙে যেত।
router = APIRouter()


class WorkspaceCommand(BaseModel):
    prompt: str
    project_id: str


class PRRequest(BaseModel):
    user_id: str
    repo_name: str  # e.g., "paykaribazaronline/supremeai"
    file_path: str
    code: str
    prompt: str


class LearnRequest(BaseModel):
    prompt: str
    working_code: str


@router.post("/agent/execute")
async def execute_agent_command(
    command: WorkspaceCommand, _user: dict = Depends(get_current_user_token)
):
    # 🟢 Step 1: Zero-Cost Memory Check (Project Auto-Didact)
    # বাংলা মন্তব্য: user_id যোগ করা হয়েছে tenant-scoped memory জন্য (cache poisoning প্রতিরোধ)
    # একই prompt-এর জন্য ভিন্ন ইউজাররা ভিন্ন সমাধান পাবে
    user_id = _user.get("sub", "anonymous")
    cached_solution = get_from_memory(command.prompt, user_id=user_id)
    if cached_solution:
        return {
            "status": "success",
            "source": "memory",  # মেমোরি থেকে আসায় এপিআই খরচ ০!
            "message": "Found in local memory.",
            "code": cached_solution,
        }

    # 🔴 Step 2: Premium API Escalation (যদি মেমোরিতে না পায়)
    logger.info("⚠️ Pattern not recognized. Escalating to Premium AI...")

    # এখানে আপনার OpenAI বা Claude এপিআই কল করার লজিক বসবে
    # ডামি রেসপন্স (টেস্টিংয়ের জন্য):
    ai_generated_code = (
        f"// Code generated by AI for: {command.prompt}\nconsole.log('Hello World');"
    )

    # 🧠 Step 3: Learn and Save (AI-এর সমাধানটি মেমোরিতে সেভ করে রাখবে)
    # save_to_memory এখন /agent/learn এ করা হয়, এখানে না

    return {
        "status": "success",
        "source": "ai_api",
        "message": "Generated via AI (not saved to memory yet).",
        "code": ai_generated_code,
    }


@router.post("/agent/learn")
async def commit_to_memory(request: LearnRequest, _user: dict = Depends(get_current_user_token)):
    """
    শুধুমাত্র ভেরিফায়েড এবং কাজ করা কোডগুলোই মেমোরি ভল্টে সেভ হবে।
    বাংলা মন্তব্য: user_id যোগ করা হয়েছে tenant-scoped memory জন্য (cache poisoning প্রতিরোধ)
    """
    user_id = _user.get("sub", "anonymous")
    save_to_memory(request.prompt, request.working_code, user_id=user_id)
    logger.info(
        f"🧠 [Auto-Didact] Verified solution saved for prompt: {request.prompt[:30]}... (user: {user_id})"
    )
    return {"status": "success", "message": "Memorized successfully"}


from tools.devops.github_agent import create_autonomous_pr


@router.post("/agent/github/pr")
async def trigger_github_pr(request: PRRequest):
    try:
        commit_msg = f"Implemented: {request.prompt[:50]}..."
        pr_url = await create_autonomous_pr(
            user_id=request.user_id,
            repo_name=request.repo_name,
            file_path=request.file_path,
            code_content=request.code,
            commit_msg=commit_msg,
        )
        return {"status": "success", "pr_url": pr_url}
    except Exception as e:
        return {"status": "error", "message": str(e)}


@router.websocket("/agent/terminal-stream")
async def terminal_stream(websocket: WebSocket):
    # AUD-2.1: previously any anonymous client could open this terminal stream.
    # A valid token (query param or first auth message) is now required.
    user = await authenticate_websocket(websocket, websocket.query_params.get("token"))
    if user is None:
        return
    await websocket.accept()
    try:
        # এটি একটি ডামি স্ট্রিম। পরবর্তীতে আমরা এখানে docker_sandbox বা WebContainers-এর লগ স্ট্রিম করব।
        await websocket.send_text(
            "\r\n[System] Secure connection established with SupremeAI Agent.\r\n"
        )

        while True:
            # ক্লায়েন্ট থেকে কোনো কমান্ড আসলে রিসিভ করা (যদি টার্মিনালে ইউজার কিছু টাইপ করে)
            data = await websocket.receive_text()

            # ইকো করা (আপাতত)
            await websocket.send_text(f"\r\n$ {data}\r\n")

            # প্রসেসিং সিমুলেট করা
            await asyncio.sleep(0.5)
            await websocket.send_text("[Agent] Processing command in Zero-Cost Environment...\r\n")

    except WebSocketDisconnect:
        logger.info("Terminal client disconnected.")
