const PreviewEmptyState: React.FC<{ device: 'browser' | 'mobile'; onBack: () => void }> = ({ device, onBack }) => (
  <div className="flex h-full w-full items-center justify-center rounded-2xl border border-dashed border-white/10 bg-slate-900/40 p-6">
    <div className="flex max-w-md flex-col items-center gap-3 text-center">
      <span className="flex size-12 items-center justify-center rounded-xl border border-white/10 bg-slate-900 text-slate-400">
        {device === 'browser' ? <Code size={20} /> : <Smartphone size={20} />}
      </span>
      <h3 className="text-base font-semibold text-slate-200">Nothing to preview yet</h3>
      <p className="text-sm leading-6 text-slate-500">
        Ask SupremeAI to build something — for example &quot;Build a small landing page
        in HTML&quot; — then press <span className="font-medium text-slate-300">Preview</span> on
        the generated code block. It will render here, inside{' '}
        {device === 'browser' ? 'the browser frame' : 'the phone simulator'}.
      </p>
      <button
        type="button"
        onClick={onBack}
        className="mt-1 rounded-lg border border-white/10 bg-slate-900/80 px-4 py-2 text-xs font-medium text-slate-300 transition hover:border-purple-400/40 hover:text-white"
      >
        ← Back to conversation
      </button>
    </div>
  </div>
);

export const AIStudio: React.FC = () => {
  const [input, setInput] = useState('');
  const [resumeConvId, setResumeConvId] = useState<string | null>(null);
  const [activeTab, setActiveTab] = useState<'chat' | 'preview' | 'mobile'>('chat');
  // CHAT LANDING (owner decision 2026-10-24): Chat is the landing tab with a
  // local history sidebar (mainstream-AI pattern). Home and Prompt Library
  // left the rail; users enable features from Settings/Profile.
  const [history, setHistory] = useState<StoredConversationMeta[]>([]);
  useEffect(() => {
    setHistory(listStoredConversations());
  }, [activeTab, resumeConvId]);
  const startNewChat = () => {
    const freshId = `conv-${Date.now()}-${Math.random().toString(36).slice(2, 8)}`;
    setResumeConvId(freshId);
  };
  const [code, setCode] = useState(CODE_PLACEHOLDER);
  const hasPreview = code.trim() !== '' && code !== CODE_PLACEHOLDER;
  // AUTO/MANUAL PREVIEW MODE (owner request 2026-10-24): mode + manual code দুটোই
  // localStorage-এ টিকে থাকে — রিফ্রেশে ইউজারের নিজের লেখা কাজ হারায় না।
  const [previewMode, setPreviewMode] = useState<'auto' | 'manual'>(() =>
    (localStorage.getItem(PREVIEW_MODE_STORE) === 'manual' ? 'manual' : 'auto'));
  const [manualCode, setManualCode] = useState<string>(() =>
    localStorage.getItem(MANUAL_CODE_STORE) ?? MANUAL_STARTER);
  useEffect(() => { localStorage.setItem(PREVIEW_MODE_STORE, previewMode); }, [previewMode]);
  useEffect(() => { localStorage.setItem(MANUAL_CODE_STORE, manualCode); }, [manualCode]);
  const [searchParams, setSearchParams] = useSearchParams();
  const intentConsumedRef = useRef(false);

  // বাংলা মন্তব্য (FIX intent-carryover #2519): ?intent= প্যারামিটার আর auto-send হয় না —
  // আগে `void handleSend(intent)` সরাসরি AI-তে পাঠাত, ফলে attacker-চিহ্নিত URL দিয়ে
  // prompt-injection করা যেত (ব্যবহারকারী কিছু দেখার আগেই প্রম্পট execute)। Root-cause
  // fix: প্যারামটি consume করে composer input-এ prefill + focus করা হয়, যাতে ব্যবহারকারী
  // টেক্সট নিজের চোখে দেখে স্পষ্টভাবে Send চাপে। ref guard StrictMode-এর double
  // effect-invoke-এ দ্বিগুণ prefill আটকায়; param strip (replace) রিফ্রেশে re-fire করে না।
  // CONVERSATION RESUME (owner request 2026-10-24): history-rail links carry
  // ?conversation=<id> — the Studio reopens that conversation with its full
  // locally-persisted message history instead of only prefilling a prompt.
  useEffect(() => {
    const conv = searchParams.get('conversation');
    if (!conv || intentConsumedRef.current) return;
    intentConsumedRef.current = true;
    setSearchParams({}, { replace: true });
    setResumeConvId(conv);
  }, [searchParams, setSearchParams]);

  useEffect(() => {
    if (intentConsumedRef.current) return;
    const intent = searchParams.get('intent');
    if (!intent) return;
    intentConsumedRef.current = true;
    setSearchParams({}, { replace: true });
    setInput(intent);
    document.querySelector<HTMLInputElement>('[data-testid="chat-input"]')?.focus();
  }, [searchParams, setSearchParams]);

  return (
    <div className="relative flex h-full w-full flex-col overflow-hidden bg-[var(--sa-canvas)] text-[var(--sa-ink)]">
      <div className="pointer-events-none absolute inset-x-0 top-0 h-48 bg-[radial-gradient(circle_at_50%_0%,rgba(34,211,238,0.12),transparent_64%)]" aria-hidden="true" />
      {/* AI Studio contextual header */}
      <div className="relative flex min-h-16 shrink-0 flex-wrap items-center justify-between gap-2 border-b border-[var(--sa-border)] bg-[var(--sa-surface)]/80 px-4 backdrop-blur sm:px-6">
        <div className="flex items-center gap-4 text-xs font-medium">
          <button 
            type="button"
            onClick={() => setActiveTab('chat')}
            className={`flex items-center gap-2 rounded-[var(--sa-radius-sm)] border px-3 py-2 text-xs transition-colors ${activeTab === 'chat' ? 'border-[var(--sa-primary)] bg-[var(--sa-primary-soft)] text-[var(--sa-primary)]' : 'border-transparent text-[var(--sa-ink-muted)] hover:border-[var(--sa-border)] hover:bg-[var(--sa-surface-raised)] hover:text-[var(--sa-ink)]'}`}
          >
            <Bot size={14} /> Conversation
          </button>
          <button 
            type="button"
            onClick={() => setActiveTab('preview')}
            className={`flex items-center gap-2 rounded-[var(--sa-radius-sm)] border px-3 py-2 text-xs transition-colors ${activeTab === 'preview' ? 'border-[var(--sa-primary)] bg-[var(--sa-primary-soft)] text-[var(--sa-primary)]' : 'border-transparent text-[var(--sa-ink-muted)] hover:border-[var(--sa-border)] hover:bg-[var(--sa-surface-raised)] hover:text-[var(--sa-ink)]'}`}
          >
            <Code size={14} /> Browser Preview
          </button>
          <button 
            type="button"
            onClick={() => setActiveTab('mobile')}
            className={`flex items-center gap-2 rounded-[var(--sa-radius-sm)] border px-3 py-2 text-xs transition-colors ${activeTab === 'mobile' ? 'border-[var(--sa-primary)] bg-[var(--sa-primary-soft)] text-[var(--sa-primary)]' : 'border-transparent text-[var(--sa-ink-muted)] hover:border-[var(--sa-border)] hover:bg-[var(--sa-surface-raised)] hover:text-[var(--sa-ink)]'}`}
          >
            <Smartphone size={14} /> Mobile Simulator
          </button>
        </div>
        
        <div className="hidden items-center gap-4 text-[10px] uppercase tracking-widest text-[var(--sa-ink-muted)] sm:flex">
          <span className="flex items-center gap-1.5"><span className="size-1.5 rounded-full bg-emerald-400" />Agent: SupremeAI</span>
          <span className="flex items-center gap-1.5"><span className="size-1.5 rounded-full bg-[var(--sa-primary)]" />Model: Configured backend</span>
          <span className="rounded-full border border-[var(--sa-border)] px-2 py-1 text-[var(--sa-ink-muted)]">Context ready</span>
        </div>
      </div>

      <div className="flex-1 min-h-0 relative">
        {activeTab === 'chat' && (
          <div className="absolute inset-0 flex gap-4 p-4">
            {/* Unified Chat Phase 2: uses the canonical UnifiedChatPanel with live streaming,
                thinking indicator, brand badge, and intent carry-over */}
            <aside className="hidden w-56 shrink-0 flex-col gap-2 md:flex" data-testid="chat-history-rail">
              <button
                type="button"
                onClick={startNewChat}
                className="inline-flex items-center justify-center gap-2 rounded-xl border border-white/10 bg-slate-900/80 px-3 py-2.5 text-sm font-medium text-slate-200 transition hover:border-purple-400/40 hover:text-white"
              >
                <MessageSquarePlus size={15} /> New chat
              </button>
              <div className="flex min-h-0 flex-1 flex-col overflow-y-auto rounded-xl border border-white/10 bg-slate-900/40 p-2">
                <p className="px-2 pb-1 text-[10px] font-semibold uppercase tracking-wider text-slate-500">Recent</p>
                {history.length === 0 ? (
                  <p className="px-2 py-2 text-xs text-slate-500">Your conversations will appear here once you start chatting.</p>
                ) : (
                  <ul className="flex flex-col gap-1">
                    {history.map((h) => (
                      <li key={h.id}>
                        <button
                          type="button"
                          onClick={() => setResumeConvId(h.id)}
                          className={`w-full rounded-lg border px-2.5 py-2 text-left text-xs transition ${
                            h.id === resumeConvId
                              ? 'border-purple-500/40 bg-purple-500/10 text-slate-100'
                              : 'border-transparent text-slate-400 hover:border-white/10 hover:bg-white/[0.03] hover:text-slate-200'
                          }`}
                          title={h.title}
                        >
                          <span className="block truncate">{h.title}</span>
                          <span className="mt-0.5 block text-[10px] text-slate-600">
                            {new Date(h.updatedAt).toLocaleDateString()}
                          </span>
                        </button>
                      </li>
                    ))}
                  </ul>
                )}
              </div>
            </aside>
            <div className="relative min-w-0 flex-1">
            <UnifiedChatPanel
              key={resumeConvId ?? 'new'}
              fit="fill"
              initialConversationId={resumeConvId ?? undefined}
              showStarter={true}
              initialInput={input}
              onInputChange={setInput}
              onPreview={(html) => {
                setCode(html);
                setActiveTab('preview');
              }}
            />
            </div>
          </div>
        )}

        {activeTab === 'preview' && (
          <div className="absolute inset-0 flex flex-col gap-3 p-4">
            <PreviewModeToggle mode={previewMode} onChange={setPreviewMode} />
            {previewMode === 'manual' ? (
              <ManualWorkbench device="browser" code={manualCode} onChange={setManualCode} />
            ) : hasPreview ? (
              <BrowserPreview html={code} />
            ) : (
              <PreviewEmptyState device="browser" onBack={() => setActiveTab('chat')} />
            )}
          </div>
        )}

        {activeTab === 'mobile' && (
          <div className="absolute inset-0 flex flex-col gap-3 p-4">
            <PreviewModeToggle mode={previewMode} onChange={setPreviewMode} />
            {previewMode === 'manual' ? (
              <ManualWorkbench device="mobile" code={manualCode} onChange={setManualCode} />
            ) : hasPreview ? (
              <MobilePreviewPanel html={code} />
            ) : (
              <PreviewEmptyState device="mobile" onBack={() => setActiveTab('chat')} />
            )}
          </div>
        )}
      </div>
    </div>
  );
};
