#!/usr/bin/env python3
"""tests/test_lockfile_promise_guard.py — standing suite for the lockfile promise guard.

বাংলা: scripts/ci/lockfile_promise_guard.py হলো #3481 (scout R83) / #1745 (R29
uv lane)-এর U6 ট্রিপওয়্যার — requirements-dev.txt হেডারের দুটো প্রতিশ্রুতি
(P1: CI lock থেকে ইনস্টল করে; P2: freshness recompile+diff) কে মেকানিক্যালি
যাচাই করে, যাতে "promised-but-absent surface" ক্লাস (U4 doc-plane variant)
আর কখনো চুপচাপ রিগ্রেস না করে।

Design (zero-dependency doctrine, dual mode — pytest + stdlib runners):
  - pytest:  pytest tests/test_lockfile_promise_guard.py
  - stdlib:  python3 tests/test_lockfile_promise_guard.py

ACTIVE plane (red on violation, green on pristine main):
  A1  lock presence + uv-autogen provenance header
  A2  txt↔lock pin consistency (missing dep / version drift = red)
  A3  uv উপলব্ধ হলে hermetic recompile→body-diff; না থাকলে honest skip
PENDING HANDOFF (skip-with-pointer; the sequencing-honesty doctrine):
  B1  pipeline.yml lock-install wiring — 0 refs = skip+admin recipe;
      একবার refs>0 হলে গার্ড স্থায়ীভাবে এনফোর্স করে (txt-installs = red)।

Every test is offline and hermetic (synthetic fixtures in temp dirs);
the live-repo run is asserted PASS-only-when-green so a drifted main
fails loudly here before CI does.
"""
from __future__ import annotations

import importlib.util
import subprocess
import sys
from pathlib import Path

import pytest

REPO = Path(__file__).resolve().parents[1]
GUARD = REPO / "scripts" / "ci" / "lockfile_promise_guard.py"

_spec = importlib.util.spec_from_file_location("lpg", GUARD)
lpg = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(lpg)  # type: ignore[union-attr]

AUTOGEN = (
    "# This file was autogenerated by uv via the following command:\n"
    "#    uv pip compile requirements-dev.txt -o requirements-dev.lock\n"
)
GOOD_TXT = "import-linter==2.15\n"
GOOD_LOCK = AUTOGEN + (
    "click==8.5.0\n    # via import-linter\n"
    "import-linter==2.15\n    # via -r requirements-dev.txt\n"
    "rich==15.0.0\n    # via import-linter\n"
)


def _fixture(tmp_path: Path, txt: str, lock: str) -> tuple[Path, Path]:
    (tmp_path / lpg.TXT_REL).write_text(txt, encoding="utf-8")
    (tmp_path / lpg.LOCK_REL).write_text(lock, encoding="utf-8")
    return tmp_path / lpg.TXT_REL, tmp_path / lpg.LOCK_REL


# ---------------------------------------------------------------------------
# A1 — presence + provenance
# ---------------------------------------------------------------------------

def test_a1_green_on_consistent_pair(tmp_path: Path) -> None:
    txt, lock = _fixture(tmp_path, GOOD_TXT, GOOD_LOCK)
    assert lpg.check_lock_presence(txt, lock) == []


def test_a1_red_on_missing_lock(tmp_path: Path) -> None:
    txt = tmp_path / lpg.TXT_REL
    txt.write_text(GOOD_TXT, encoding="utf-8")
    problems = lpg.check_lock_presence(txt, tmp_path / lpg.LOCK_REL)
    assert any("A1 FAIL" in p and "missing" in p for p in problems)


def test_a1_red_on_lost_autogen_header(tmp_path: Path) -> None:
    txt, lock = _fixture(tmp_path, GOOD_TXT, "import-linter==2.15\n")
    problems = lpg.check_lock_presence(txt, lock)
    assert any("autogen" in p for p in problems)


# ---------------------------------------------------------------------------
# A2 — pin consistency
# ---------------------------------------------------------------------------

def test_a2_green_on_consistent_pair(tmp_path: Path) -> None:
    txt, lock = _fixture(tmp_path, GOOD_TXT, GOOD_LOCK)
    assert lpg.check_consistency(txt, lock) == []


def test_a2_red_on_missing_direct_dep(tmp_path: Path) -> None:
    orphan_lock = AUTOGEN + "rich==15.0.0\n    # via import-linter\n"
    txt, lock = _fixture(tmp_path, GOOD_TXT, orphan_lock)
    problems = lpg.check_consistency(txt, lock)
    assert any("A2 FAIL" in p and "absent" in p for p in problems)


def test_a2_red_on_version_drift(tmp_path: Path) -> None:
    drifted_lock = AUTOGEN + "import-linter==2.14\n    # via -r requirements-dev.txt\n"
    txt, lock = _fixture(tmp_path, "import-linter==2.15\n", drifted_lock)
    problems = lpg.check_consistency(txt, lock)
    assert any("version drift" in p for p in problems)


# ---------------------------------------------------------------------------
# split_lock edge cases (the uv lock has NO blank line after the header)
# ---------------------------------------------------------------------------

def test_split_lock_handles_headerless_blankless_uv_lock() -> None:
    header, body = lpg.split_lock(GOOD_LOCK)
    assert header and header[0].startswith(lpg.AUTOGEN_HEADER_PREFIX)
    assert any(l.startswith("click==") for l in body), "body must survive past the header"


def test_parse_pins_ignores_via_comments() -> None:
    pins = lpg.parse_pins("import-linter==2.15\n    # via -r requirements-dev.txt\n# full comment\n")
    assert pins == [("import-linter", "2.15")]


# ---------------------------------------------------------------------------
# A3 — freshness (honest-skip when uv absent; verified when present)
# ---------------------------------------------------------------------------

def test_a3_honest_skip_or_verified(tmp_path: Path) -> None:
    """বাংলা: uv থাকলে যাচাই-মোড (fail হলে লাল), না থাকলে সৎ-স্কিপ — দুটোই বৈধ।"""
    mode, problems = lpg.check_freshness(REPO, lpg.TXT_REL, lpg.LOCK_REL)
    if mode == "verified":
        assert not any(p.startswith("A3 FAIL") for p in problems), problems
    else:
        assert any(p.startswith("A3 SKIP") for p in problems), problems


# ---------------------------------------------------------------------------
# B1 — pending handoff / enforced wiring
# ---------------------------------------------------------------------------

def _pipeline(tmp_path: Path, content: str) -> Path:
    (tmp_path / lpg.PIPELINE_REL).parent.mkdir(parents=True, exist_ok=True)
    (tmp_path / lpg.PIPELINE_REL).write_text(content, encoding="utf-8")
    return tmp_path


def test_b1_skip_with_pointer_at_zero_refs(tmp_path: Path) -> None:
    _pipeline(tmp_path, "run: pip install -r requirements-dev.txt\n")
    problems = lpg.check_pipeline_wiring(tmp_path)
    assert any(p.startswith("B1 SKIP") for p in problems)
    assert any("ADMIN RECIPE" in p for p in problems)


def test_b1_enforced_red_on_stray_txt_install(tmp_path: Path) -> None:
    _pipeline(
        tmp_path,
        "run: pip install -r requirements-dev.lock\n"
        "run: pip install -r requirements-dev.txt\n",
    )
    problems = lpg.check_pipeline_wiring(tmp_path)
    assert any(p.startswith("B1 FAIL") for p in problems)


def test_b1_enforced_green_on_lock_install(tmp_path: Path) -> None:
    _pipeline(tmp_path, "run: pip install -r requirements-dev.lock\n")
    problems = lpg.check_pipeline_wiring(tmp_path)
    assert any(p.startswith("B1 PASS") for p in problems), problems


# ---------------------------------------------------------------------------
# Live repo + hermetic self-test + CLI contract
# ---------------------------------------------------------------------------

def test_self_test_hermetic_suite_passes() -> None:
    proc = subprocess.run(
        [sys.executable, str(GUARD), "--self-test"],
        capture_output=True, text=True, timeout=120,
    )
    assert proc.returncode == 0, proc.stdout + proc.stderr
    assert "PASS (hermetic)" in proc.stdout


def test_live_repo_run_passes_on_pristine_main() -> None:
    """বাংলা: প্রিস্টিন main-এ এনফোর্সড-প্লেন সবুজ হতে হবে — এটাই স্ট্যান্ডিং গার্ড।"""
    proc = subprocess.run(
        [sys.executable, str(GUARD)],
        capture_output=True, text=True, timeout=240,
        cwd=str(REPO),
    )
    assert proc.returncode == 0, proc.stdout + proc.stderr
    assert "PASS" in proc.stdout


def test_cli_exit_contract(tmp_path: Path) -> None:
    """--repo-root অ্যান্ড ফেইল-ক্লোজড exit 1 (অনুপস্থিত ভিত্তিতে rc=2)।"""
    empty = tmp_path / "empty"
    empty.mkdir()
    proc = subprocess.run(
        [sys.executable, str(GUARD), "--repo-root", str(empty)],
        capture_output=True, text=True, timeout=60,
    )
    assert proc.returncode == 1  # missing both files = enforced A1 red


if __name__ == "__main__":
    sys.exit(pytest.main([__file__, "-v"]))
