#!/usr/bin/env python3
"""SupremeAI — Lockfile Promise Guard (U6 tripwire for the #1745/#3481 doc-plane class).

বাংলা: requirements-dev.txt-এর হেডার (PR #3104) দুটো টেস্টেবল প্রতিশ্রুতি দেয়:
  P1: requirements-dev.lock = "the reproducible resolution CI installs from"
  P2: freshness "CI-enforced ... recompile to a temp path and diff the bodies"
scout(R83) #3481 বাইট-লেভেলে প্রমাণ করেছে দুটোই unwired (pipeline.yml লুজ txt
ইনস্টল করে; recompile+diff স্টেপ অস্তিত্বহীন)। এই গার্ড সেই প্রতিশ্রুতিকে
মেকানিক্যালি যাচাই করে — "machine-checked, not prose" — এবং U6-ক্লাস
(header-promises-CI-enforcement-without-a-guard) পুনরাবৃত্তি আটকায়।

Doctrine (test_ci_supply_chain_guard.py পরিবার):
  ACTIVE (pristine main-এ সবুজ, ভায়োলেশনে লাল):
    A1  lock ফাইল আছে এবং uv-autogen হেডার বহন করে;
    A2  txt-এর প্রতিটা direct-dep pin lock-বডিতে অক্ষত ও same-version (ড্রিফট লাল);
    A3  uv পাওয়া গেলে hermetic recompile→body-diff (P2-র বাস্তব যাচাই);
        uv না থাকলে SKIP-with-evidence (সৎ অন্ধকার — কখনো মিথ্যা PASS নয়)।
  PENDING HANDOFF (SKIP with pointer — pending state, not a regression):
    B1  pipeline.yml lock-install wiring। রেফারেন্স 0 হলে skip+recipe; একবার
        admin ওয়্যার করলে (refs>0) গার্ড স্থায়ীভাবে এনফোর্স করবে — txt-ref
        থাকলে লাল (হেডার-প্রতিশ্রুতি ভাঙা), lock-ref থাকলে সবুজ।
  ADMIN RECIPE (deployment-side, .github/** protected — bridge-able নয়):
    pipeline.yml fast-lint জবে: `pip install -r requirements-dev.lock`
    (flat pin list, pip-compatible); তারপর B1 নিজেই এনফোর্স মোডে চলবে।

Zero-Recurrence note (#3481): এই গার্ড নিজেই সেই ফিক্স — প্রতিশ্রুতি আর বাস্তবতা
এদিক থেকে আর চুপচাপ আলাদা হতে পারবে।

Usage:
  python3 scripts/ci/lockfile_promise_guard.py                # repo-root যাচাই (CI/প্রিপুশ)
  python3 scripts/ci/lockfile_promise_guard.py --self-test    # hermetic offline suite
Exit codes: 0 = pass/skip-with-evidence, 1 = enforced-check ব্যর্থ, 2 = ভিত্তি অনুপস্থিত।
"""
from __future__ import annotations

import argparse
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]
TXT_REL = "requirements-dev.txt"
LOCK_REL = "requirements-dev.lock"
PIPELINE_REL = Path(".github") / "workflows" / "pipeline.yml"

AUTOGEN_HEADER_PREFIX = "# This file was autogenerated by uv"
PIN_RE = re.compile(r"^([A-Za-z0-9._-]+)==([^\s]+)\s*$")
LOCK_BODY_LINE_RE = re.compile(r"^([A-Za-z0-9._-]+)==([^\s]+)")
VIA_COMMENT_RE = re.compile(r"^\s+# via ", re.IGNORECASE)


def parse_pins(text: str) -> list[tuple[str, str]]:
    """বাংলা: নন-কমেন্ট `pkg==ver` লাইন → (pkg, ver) তালিকা; via-কমেন্ট লাইন বাদ।"""
    pins: list[tuple[str, str]] = []
    for raw in text.splitlines():
        line = raw.strip()
        if not line or line.startswith("#") or VIA_COMMENT_RE.match(raw):
            continue
        m = PIN_RE.match(line)
        if m:
            pins.append((m.group(1).lower(), m.group(2)))
    return pins


def split_lock(text: str) -> tuple[list[str], list[str]]:
    """বাংলা: lock → (autogen-হেডার-লাইন, বডি-লাইন)। বাস্তব uv-লক-এ হেডারের পরে
    ফাঁকা লাইন থাকে না — হেডার = ফাইল-শুরুর ধারাবাহিক `#`-কমেন্ট লাইন; প্রথম
    নন-কমেন্ট লাইন থেকে বডি। (self-test কেস-১ এই এজ-কেসটাই ধরেছিল।)"""
    lines = text.splitlines()
    header: list[str] = []
    body: list[str] = []
    for i, line in enumerate(lines):
        if line.startswith("#") and not body:
            header.append(line)
        else:
            body.extend(lines[i:])
            break
    return header, body


def check_lock_presence(txt_path: Path, lock_path: Path) -> list[str]:
    """A1: ভিত্তি ফাইল দুটির অস্তিত্ব ও autogen হেডার।"""
    problems: list[str] = []
    if not txt_path.exists():
        problems.append(f"A1 FAIL: {TXT_REL} missing (guard premise broken)")
    if not lock_path.exists():
        problems.append(f"A1 FAIL: {LOCK_REL} missing — header promises a lock; deletion = red")
    else:
        header, _ = split_lock(lock_path.read_text(encoding="utf-8"))
        if not any(l.startswith(AUTOGEN_HEADER_PREFIX) for l in header):
            problems.append(
                f"A1 FAIL: {LOCK_REL} lost the uv-autogen header — recompile to restore provenance"
            )
    return problems


def check_consistency(txt_path: Path, lock_path: Path) -> list[str]:
    """A2: txt-এর প্রতিটা direct-dep lock-বডিতে same-version পিনড থাকতে হবে।"""
    problems: list[str] = []
    lock_body = split_lock(lock_path.read_text(encoding="utf-8"))[1]
    lock_pins = {pkg: ver for pkg, ver in (LOCK_BODY_LINE_RE.match(l).groups()
                 for l in map(str.strip, lock_body) if LOCK_BODY_LINE_RE.match(l))}
    for pkg, ver in parse_pins(txt_path.read_text(encoding="utf-8")):
        if pkg not in lock_pins:
            problems.append(
                f"A2 FAIL: direct dep '{pkg}=={ver}' pinned in {TXT_REL} but absent from {LOCK_REL} "
                "(lock drift — recompile: uv pip compile requirements-dev.txt -o requirements-dev.lock)"
            )
        elif lock_pins[pkg] != ver:
            problems.append(
                f"A2 FAIL: version drift for '{pkg}' — {TXT_REL} pins {ver}, {LOCK_REL} pins {lock_pins[pkg]}"
            )
    return problems


def check_freshness(repo_root: Path, txt_rel: str, lock_rel: str) -> tuple[str, list[str]]:
    """A3 (P2-র বাস্তব যাচাই): uv থাকলে temp-এ recompile→body-diff।
    রিটার্ন: (mode, problems) — mode ∈ {"verified", "skipped"}।"""
    uv = shutil.which("uv")
    if not uv:
        return "skipped", [
            "A3 SKIP (honest-dark): 'uv' not on PATH — recompile+diff freshness check not run; "
            "P2 remains machine-verified the moment uv is available (never a silent pass)"
        ]
    txt = repo_root / txt_rel
    lock = repo_root / lock_rel
    with tempfile.TemporaryDirectory(prefix="lockguard-") as td:
        out = Path(td) / "recompiled.lock"
        proc = subprocess.run(
            [uv, "pip", "compile", str(txt), "-o", str(out), "--quiet"],
            cwd=str(repo_root), capture_output=True, text=True, timeout=180,
        )
        if proc.returncode != 0:
            return "skipped", [
                f"A3 SKIP (honest-dark): uv recompile failed (rc={proc.returncode}): "
                f"{(proc.stderr or '').strip()[:300]}"
            ]
        if not out.exists():
            return "skipped", ["A3 SKIP (honest-dark): uv produced no output file"]
        want_body = split_lock(lock.read_text(encoding="utf-8"))[1]
        got_body = split_lock(out.read_text(encoding="utf-8"))[1]
        if want_body != got_body:
            diff_pkgs = sorted({
                pkg for body in (want_body, got_body)
                for pkg, _ in (LOCK_BODY_LINE_RE.match(l).groups()
                               for l in map(str.strip, body) if LOCK_BODY_LINE_RE.match(l))
            })
            return "verified", [
                f"A3 FAIL: recompiled lock body diverges from committed {LOCK_REL} "
                f"(first diverging pins among: {', '.join(diff_pkgs[:8])}) — "
                "lock is stale vs txt; recompile and commit"
            ]
        return "verified", []


def check_pipeline_wiring(repo_root: Path) -> list[str]:
    """B1 (PENDING HANDOFF): pipeline-এর lock-রেফারেন্স।
    refs==0 → skip-with-pointer; refs>0 → এনফোর্স: lock-কেই রেফার করতে হবে।"""
    pipeline = repo_root / PIPELINE_REL
    if not pipeline.exists():
        return ["B1 SKIP (honest-dark): pipeline.yml not found in this checkout"]
    text = pipeline.read_text(encoding="utf-8")
    lock_refs = len(re.findall(r"requirements-dev\.lock", text))
    if lock_refs == 0:
        return [
            "B1 SKIP (pending handoff): pipeline.yml has 0 references to requirements-dev.lock — "
            "header P1 ('CI installs from the lock') is currently UNWIRED (scout #3481 receipt); "
            "ADMIN RECIPE: fast-lint job → `pip install -r requirements-dev.lock`; "
            "this guard permanently enforces B1 the moment the first reference lands"
        ]
    problems: list[str] = []
    for m in re.finditer(r"pip install -r requirements-dev\.(lock|txt)", text):
        if m.group(1) == "txt":
            problems.append(
                "B1 FAIL: pipeline still installs the loose requirements-dev.txt while a lock "
                "reference exists — header P1 broken; switch the dev-tooling install to "
                "requirements-dev.lock"
            )
    for m in re.finditer(r"requirements-dev\.lock", text):
        line_no = text.count("\n", 0, m.start()) + 1
        line = text.splitlines()[line_no - 1]
        if "pip install" not in line and "compile" not in line and "uv" not in line:
            problems.append(
                f"B1 WARN: pipeline.yml:{line_no} mentions the lock outside an install/compile "
                f"context: {line.strip()[:120]}"
            )
    if not problems:
        problems.append(
            f"B1 PASS (enforced): pipeline.yml carries {lock_refs} lock reference(s) and installs "
            "the lock — header P1 is machine-verified from this run onward"
        )
    return problems


def run_checks(repo_root: Path) -> tuple[bool, list[str]]:
    """বাংলা: সব প্লেন চালায়। enforced-ফেইল হলে False।"""
    lines: list[str] = []
    ok = True
    txt = repo_root / TXT_REL
    lock = repo_root / LOCK_REL
    for p in check_lock_presence(txt, lock):
        lines.append(p)
        ok = False
    if ok:
        for p in check_consistency(txt, lock):
            lines.append(p)
            ok = False
        mode, probs = check_freshness(repo_root, TXT_REL, LOCK_REL)
        for p in probs:
            lines.append(p)
            if p.startswith("A3 FAIL"):
                ok = False
        for p in check_pipeline_wiring(repo_root):
            lines.append(p)
            if p.startswith("B1 FAIL"):
                ok = False
    for line in lines:
        print(line)
    print(
        "lockfile_promise_guard: "
        + ("PASS (enforced checks green; pending handoffs declared)"
           if ok else "FAIL (enforced check red)")
    )
    return ok, lines


# ---------------------------------------------------------------------------
# Hermetic self-test (guard-the-guard) — zero network, zero repo mutation
# ---------------------------------------------------------------------------

def self_test() -> bool:
    """বাংলা: ৬-কেস হারমেটিক স্যুট — সিনথেটিক ফিক্সচারে প্রতিটা প্লেনের সবুজ/লাল পথ।"""
    import os

    cases: list[tuple[str, bool]] = []
    tmp = Path(tempfile.mkdtemp(prefix="lockguard-selftest-"))
    try:
        good_txt = "import-linter==2.15\n"
        good_lock = (
            "# This file was autogenerated by uv via the following command:\n"
            "#    uv pip compile requirements-dev.txt -o requirements-dev.lock\n"
            "click==8.5.0\n    # via import-linter\n"
            "import-linter==2.15\n    # via -r requirements-dev.txt\n"
            "rich==15.0.0\n    # via import-linter\n"
        )
        # কেস-১: সামঞ্জস্যপূর্ণ জোড়া → A2 সবুজ
        d1 = tmp / "case1"; d1.mkdir()
        (d1 / TXT_REL).write_text(good_txt, encoding="utf-8")
        (d1 / LOCK_REL).write_text(good_lock, encoding="utf-8")
        c1 = check_consistency(d1 / TXT_REL, d1 / LOCK_REL)
        cases.append(("A2 green on consistent pair", not c1))
        # কেস-২: lock-এ direct-dep অনুপস্থিত → লাল
        d2 = tmp / "case2"; d2.mkdir()
        (d2 / TXT_REL).write_text(good_txt, encoding="utf-8")
        (d2 / LOCK_REL).write_text(
            "# This file was autogenerated by uv via the following command:\n"
            "#    uv pip compile requirements-dev.txt -o requirements-dev.lock\n"
            "rich==15.0.0\n    # via import-linter\n", encoding="utf-8")
        c2 = check_consistency(d2 / TXT_REL, d2 / LOCK_REL)
        cases.append(("A2 red on missing direct dep", any("A2 FAIL" in p and "absent" in p for p in c2)))
        # কেস-৩: সংস্করণ-ড্রিফট → লাল
        d3 = tmp / "case3"; d3.mkdir()
        (d3 / TXT_REL).write_text("import-linter==2.16\n", encoding="utf-8")
        (d3 / LOCK_REL).write_text(
            "# This file was autogenerated by uv via the following command:\n"
            "#    uv pip compile requirements-dev.txt -o requirements-dev.lock\n"
            "import-linter==2.15\n    # via -r requirements-dev.txt\n", encoding="utf-8")
        c3 = check_consistency(d3 / TXT_REL, d3 / LOCK_REL)
        cases.append(("A2 red on version drift", any("version drift" in p for p in c3)))
        # কেস-৪: autogen হেডার হারালে A1 লাল
        d4 = tmp / "case4"; d4.mkdir()
        (d4 / TXT_REL).write_text(good_txt, encoding="utf-8")
        (d4 / LOCK_REL).write_text("import-linter==2.15\n", encoding="utf-8")
        c4 = check_lock_presence(d4 / TXT_REL, d4 / LOCK_REL)
        cases.append(("A1 red on missing autogen header", any("autogen" in p for p in c4)))
        # কেস-৫: wiring — লক-রেফ ছাড়া pipeline → skip-with-pointer (এনফোর্স নয়)
        d5 = tmp / "case5"; d5.mkdir()
        (d5 / PIPELINE_REL).parent.mkdir(parents=True)
        (d5 / PIPELINE_REL).write_text("run: pip install -r requirements-dev.txt\n", encoding="utf-8")
        c5 = check_pipeline_wiring(d5)
        cases.append(("B1 skip-with-pointer at 0 refs", any(p.startswith("B1 SKIP") for p in c5)))
        # কেস-৬: wiring — lock রেফ + txt ইনস্টল সমান্তরালে → এনফোর্সড লাল
        d6 = tmp / "case6"; d6.mkdir()
        (d6 / PIPELINE_REL).parent.mkdir(parents=True)
        (d6 / PIPELINE_REL).write_text(
            "run: pip install -r requirements-dev.lock\nrun: pip install -r requirements-dev.txt\n",
            encoding="utf-8")
        c6 = check_pipeline_wiring(d6)
        cases.append(("B1 enforced-red on stray txt install", any(p.startswith("B1 FAIL") for p in c6)))
    finally:
        shutil.rmtree(tmp, ignore_errors=True)

    failed = [name for name, passed in cases if not passed]
    for name, passed in cases:
        print(f"  [{'PASS' if passed else 'FAIL'}] {name}")
    if failed:
        print(f"self-test FAILED: {failed}")
        return False
    print(f"self-test: {len(cases)}/{len(cases)} PASS (hermetic)")
    return True


def main() -> int:
    parser = argparse.ArgumentParser(description="Lockfile promise guard (#3481/#1745 U6 tripwire)")
    parser.add_argument("--self-test", action="store_true",
                        help="hermetic offline fixture suite (guard-the-guard)")
    parser.add_argument("--repo-root", type=str, default="",
                        help="override repo root (tests use temp fixtures)")
    args = parser.parse_args()

    if args.self_test:
        return 0 if self_test() else 1

    root = Path(args.repo_root).resolve() if args.repo_root else REPO_ROOT
    ok, _ = run_checks(root)
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
