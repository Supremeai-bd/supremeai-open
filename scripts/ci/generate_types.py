#!/usr/bin/env python3
"""generate_types.py — deterministic OpenAPI → TypeScript + Python type generation (issue #375, Phase 4).

Contract-drift killer (#375 anti-pattern 6): the OpenAPI document
``api-schemas/gateway.openapi.yaml`` is the single source of truth (SSOT) for
the gateway wire contract; hand-typed TypeScript interfaces in
mcp-control-plane and Python dataclasses in examples/ duplicate its fields by
hand and silently drift. This generator replaces that duplication: it lints
the SSOT on the raw text and again after parse (both fail-closed — a malformed
SSOT aborts with a line/path-annotated error; the live main defect
``required: essages]`` was caught exactly this way the day this guard was
written), then deterministically emits:

  * TypeScript interfaces (one per ``components.schemas`` entry), and
  * Python TypedDicts (required fields via an inheritance split, optional via
    ``total=False``), both with a GENERATED-DO-NOT-EDIT header.

Determinism: same schema file ⇒ byte-identical output (no timestamps, no
hash-map iteration order dependence, declared-order properties). ``--check``
regenerates to a temp dir and byte-diffs against the committed outputs — CI
wires this as the zero-drift gate (the workflow edit itself is a .github/
protected path, so the wiring rides the maintainer's hand; see
docs/ISSUE_HUB_POLICY.md Appendix A lane rule).

Exit codes: 0 success/parity; 1 drift detected (--check); 2 schema/usage error
(fail-closed — never emit types from a lint-dirty SSOT).

House style: stdlib-only except PyYAML (missing ⇒ exit 2 with an actionable
message, same try/except posture as continuous_agent_loop.py); Bengali-English
contract docstrings; fail-loud, never silent.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path
from typing import Any

try:
    import yaml  # type: ignore
except ImportError:  # fail-closed, actionable
    yaml = None

TS_PRIMITIVES = {"string": "string", "integer": "number", "number": "number", "boolean": "boolean"}
PY_PRIMITIVES = {"string": "str", "integer": "int", "number": "float", "boolean": "bool"}
KNOWN_TYPES = set(TS_PRIMITIVES) | {"array", "object", "null"}
SSOT_LABEL = "api-schemas/gateway.openapi.yaml"  # canonical repo-relative SSOT path (path-stable headers)

GENERATED_HEADER = (
    "GENERATED by scripts/ci/generate_types.py from " + SSOT_LABEL + " — DO NOT EDIT BY HAND.\n"
    "Regenerate with: python3 scripts/ci/generate_types.py --schema " + SSOT_LABEL + " ...\n"
    "--check enforces byte parity in CI (issue #375 Phase 4, contract-drift killer).\n"
)


class GenerateError(Exception):
    """Fail-closed lint/generation failure with a path/line annotation."""


# ---------------------------------------------------- stage-0 raw lint ----
_RAW_REQUIRED_DEFECT = re.compile(r"^(\s*)required:\s*([^\[\s#].*)$")


def raw_lint_schemas(text: str) -> None:
    """Stage-0 fail-closed lint over the RAW TEXT of components.schemas.

    Defense-in-depth: the parsed-schema lint (lint_openapi) already rejects a
    literal-string ``required`` once the YAML loader surfaces it, but raw-text
    scanning adds (a) 1-based line-number precision for the SSOT author and
    (b) an arrest independent of any loader's scalar-recovery behavior — the
    same bytes must fail the gate no matter which YAML implementation reads
    them (the 'silent runtime break' class #375 targets). Within
    components.schemas the schema-level ``required`` keyword is array-only, so
    any ``required:`` line whose inline value does not start with '[' is a
    defect. (Operation-level ``required: true`` in paths/ lives OUTSIDE
    components.schemas and is never scanned.)
    """
    in_schemas = False
    for lineno, line in enumerate(text.splitlines(), 1):
        if re.match(r"^ {2}schemas:\s*$", line):
            in_schemas = True
            continue
        if in_schemas and re.match(r"^\S", line):  # left components (new top-level key)
            in_schemas = False
        if not in_schemas:
            continue
        m = _RAW_REQUIRED_DEFECT.match(line)
        if m:
            raise GenerateError(
                f"api-schemas line {lineno}: schema-level 'required' must be an ARRAY "
                f"('required: [field, ...]'), got {m.group(2)!r} — literal-string required "
                f"is the #375 contract-drift defect class (PyYAML silently heals it; "
                f"stricter parsers break). Fix the SSOT before generating types."
            )


# ---------------------------------------------------------------- lint ----
def _resolve_ref(root: dict[str, Any], ref: str, path: str) -> dict[str, Any]:
    if not isinstance(ref, str) or not ref.startswith("#/"):
        raise GenerateError(f"{path}: $ref must be a local '#/...' pointer, got {ref!r}")
    node: Any = root
    for part in ref[2:].split("/"):
        if not isinstance(node, dict) or part not in node:
            raise GenerateError(f"{path}: unresolvable $ref {ref!r} (missing {part!r})")
        node = node[part]
    if not isinstance(node, dict):
        raise GenerateError(f"{path}: $ref {ref!r} resolves to a non-object")
    return node


def _lint_schema(node: Any, root: dict[str, Any], path: str) -> None:
    """Fail-closed lint of the OpenAPI-schema subset this generator consumes."""
    if not isinstance(node, dict):
        raise GenerateError(f"{path}: schema must be an object, got {type(node).__name__}")
    if "$ref" in node:
        _resolve_ref(root, node["$ref"], path)
        if len(node) > 1:
            raise GenerateError(f"{path}: $ref siblings are not allowed in this strict subset")
        return
    t = node.get("type")
    if t is None:
        raise GenerateError(f"{path}: missing 'type' (subset requires explicit types)")
    if t not in KNOWN_TYPES:
        raise GenerateError(f"{path}: unknown type {t!r} (known: {sorted(KNOWN_TYPES)})")
    if "enum" in node:
        if not isinstance(node["enum"], list) or not node["enum"]:
            raise GenerateError(f"{path}: enum must be a non-empty array")
    if "const" in node and "enum" in node:
        raise GenerateError(f"{path}: const and enum are mutually exclusive in this subset")
    if "nullable" in node and not isinstance(node["nullable"], bool):
        raise GenerateError(f"{path}: nullable must be a boolean")
    if t == "array":
        if "items" not in node:
            raise GenerateError(f"{path}: array schema must declare 'items'")
        _lint_schema(node["items"], root, f"{path}.items")
    if t == "object":
        props = node.get("properties", {})
        if not isinstance(props, dict):
            raise GenerateError(f"{path}: properties must be an object")
        req = node.get("required", [])
        if not isinstance(req, list) or not all(isinstance(r, str) for r in req):
            # the exact defect class caught on main: ``required: essages]``
            raise GenerateError(
                f"{path}: required must be an ARRAY OF STRINGS, got {req!r} "
                f"(literal-string required is the #375 drift class — fix the SSOT)"
            )
        if "properties" in node or req:
            unknown = [r for r in req if r not in props]
            if unknown:
                raise GenerateError(f"{path}: required names missing from properties: {unknown}")
        for name, sub in props.items():
            _lint_schema(sub, root, f"{path}.properties.{name}")
    for key in ("default", "const"):
        if key in node and "enum" in node and node[key] not in node["enum"]:
            raise GenerateError(f"{path}: {key} {node[key]!r} not in enum {node['enum']!r}")


def lint_openapi(doc: Any) -> dict[str, Any]:
    """Lint the document envelope, then every component schema. Returns the doc."""
    if not isinstance(doc, dict):
        raise GenerateError("root: OpenAPI document must be an object")
    if not str(doc.get("openapi", "")).startswith("3."):
        raise GenerateError(f"root: openapi field must be 3.x, got {doc.get('openapi')!r}")
    comps = doc.get("components")
    if not isinstance(comps, dict) or not isinstance(comps.get("schemas"), dict) or not comps["schemas"]:
        raise GenerateError("root: components.schemas must be a non-empty object (nothing to generate)")
    for name, sch in comps["schemas"].items():
        if not name.isidentifier():
            raise GenerateError(f"components.schemas.{name}: name must be a TS/Python identifier")
        _lint_schema(sch, doc, f"components.schemas.{name}")
    return doc


# ------------------------------------------------------------ emission ----
def _ts_type(node: dict[str, Any]) -> str:
    if "$ref" in node:
        return node["$ref"].rsplit("/", 1)[-1]
    t = node["type"]
    base = TS_PRIMITIVES[t] if t in TS_PRIMITIVES else None
    if t == "array":
        base = f"Array<{_ts_type(node['items'])}>"
    elif t == "object":
        props = node.get("properties", {})
        req = set(node.get("required", []))
        if not props:
            base = "Record<string, unknown>"
        else:
            fields = "; ".join(
                f"{(n if n in req else n + '?')}: {_ts_type(s)}"
                for n, s in props.items()
            )
            base = "{ " + fields + " }"
    elif t == "null":
        base = "null"
    if base is None:  # unreachable post-lint
        raise GenerateError(f"unhandled type {t!r}")
    if "enum" in node:
        lits = " | ".join(json.dumps(v) for v in node["enum"])
        base = f"({lits})"
    if node.get("const") is not None:
        base = json.dumps(node["const"])
    if node.get("nullable"):
        base = f"({base} | null)"
    return base


def _py_annotation(node: dict[str, Any], root: dict[str, Any]) -> str:
    if "$ref" in node:
        return node["$ref"].rsplit("/", 1)[-1]
    t = node["type"]
    if t == "array":
        return f"list[{_py_annotation(node['items'], root)}]"
    if t == "object":
        props = node.get("properties", {})
        if not props:
            return "dict[str, Any]"
        # nested inline objects become deterministically named TypedDicts
        raise GenerateError("internal: nested objects must be hoisted before py emission")
    base = PY_PRIMITIVES[t]
    if "enum" in node or node.get("const") is not None:
        pass  # literal unions are runtime-lossless as the primitive type in a TypedDict
    if node.get("nullable"):
        base = f"{base} | None"
    return base


def _doc_comment(node: dict[str, Any], mark: str) -> str:
    d = str(node.get("description", "")).strip().replace("\n", " ")
    return f"  {mark} {d}" if d else ""


def emit_ts(doc: dict[str, Any], schema_rel: str = SSOT_LABEL) -> str:
    out = ["// " + GENERATED_HEADER.replace("\n", "\n// ").rstrip(), ""]
    for name, sch in doc["components"]["schemas"].items():
        if "$ref" in sch:
            out.append(f"// {name} is an alias of {sch['$ref'].rsplit('/', 1)[-1]}")
            out.append(f"export type {name} = {sch['$ref'].rsplit('/', 1)[-1]};")
            out.append("")
            continue
        c = _doc_comment(sch, "//")
        if c:
            out.append(c)
        out.append(f"export interface {name} {{")
        props = sch.get("properties", {})
        req = set(sch.get("required", []))
        for n, s in props.items():
            c = _doc_comment(s, "//")
            if c:
                out.append(c)
            out.append(f"  {n}{'?: ' if n not in req else ': '}{_ts_type(s)};")
        if not props:
            out.append("  [k: string]: unknown;")
        out.append("}")
        out.append("")
    return "\n".join(out).rstrip() + "\n"


def _hoist(name: str, node: dict[str, Any], root: dict[str, Any], defs: list[tuple[str, dict[str, Any]]]) -> str:
    """Recursively hoist inline object schemas into deterministically named TypedDicts."""
    props = node.get("properties", {})
    for n in props:
        sub = props[n]
        if isinstance(sub, dict) and "$ref" not in sub and sub.get("type") == "object":
            _hoist(f"{name}__{n}", sub, root, defs)
        if isinstance(sub, dict) and sub.get("type") == "array" and isinstance(sub["items"], dict) \
                and "$ref" not in sub["items"] and sub["items"].get("type") == "object":
            _hoist(f"{name}__{n}__item", sub["items"], root, defs)
    defs.append((name, node))
    return name


def emit_py(doc: dict[str, Any], schema_rel: str = SSOT_LABEL) -> str:
    defs: list[tuple[str, dict[str, Any]]] = []
    roots: list[tuple[str, dict[str, Any], dict[str, Any]]] = []
    for name, sch in doc["components"]["schemas"].items():
        if "$ref" in sch:
            roots.append((name, {"type": "alias", "target": sch["$ref"].rsplit("/", 1)[-1]}, sch))
            continue
        _hoist(name, sch, doc, defs)
        roots.append((name, sch, sch))
    seen = set()
    lines = ["# " + GENERATED_HEADER.replace("\n", "\n# ").rstrip(),
             "",
             "from __future__ import annotations",
             "",
             "from typing import Any, TypedDict",
             ""]
    for name, node in defs:
        if name in seen:
            continue
        seen.add(name)
        props = node.get("properties", {})
        req = list(node.get("required", []))
        ann = {}
        for n, s in props.items():
            sub = s
            if sub.get("type") == "object" and "$ref" not in sub:
                ann[n] = f"{name}__{n}"
            elif sub.get("type") == "array" and "$ref" not in sub["items"] and sub["items"].get("type") == "object":
                ann[n] = f"list[{name}__{n}__item]"
            else:
                ann[n] = _py_annotation(sub, doc)
        d = str(node.get("description", "")).strip().replace("\n", " ")
        if req:
            base = f"{name}_Required"
            lines.append(f"class {base}(TypedDict):")
            for n in req:
                lines.append(f"    {n}: {ann[n]}")
            lines.append("")
            hdr = f"class {name}({base}, total=False):"
            if d:
                hdr += f"  # {d}"
            lines.append(hdr)
            opt = [(n, a) for n, a in ann.items() if n not in req]
            for n, a in opt:
                lines.append(f"    {n}: {a}")
            if not opt:
                lines.append("    pass")
        else:
            hdr = f"class {name}(TypedDict, total=False):"
            if d:
                hdr += f"  # {d}"
            lines.append(hdr)
            for n, a in ann.items():
                lines.append(f"    {n}: {a}")
            if not ann:
                lines.append("    pass")
        lines.append("")
    for name, node, _orig in roots:
        if node.get("type") == "alias":
            lines.append(f"{name} = {node['target']}  # $ref alias")
            lines.append("")
    return "\n".join(lines).rstrip() + "\n"


# ---------------------------------------------------------------- main ----
def generate(schema_path: Path) -> tuple[str, str]:
    if yaml is None:
        raise GenerateError("PyYAML is required to parse the OpenAPI SSOT — pip install pyyaml (fail-closed: no yaml, no types)")
    text = schema_path.read_text(encoding="utf-8")
    raw_lint_schemas(text)  # stage 0: catch defects the loader could mask
    doc = yaml.safe_load(text)
    lint_openapi(doc)
    ts, py = emit_ts(doc), emit_py(doc)
    # determinism guard: regenerate and compare (same process, same input)
    ts2, py2 = emit_ts(doc), emit_py(doc)
    if (ts, py) != (ts2, py2):
        raise GenerateError("internal: emission is not deterministic")
    return ts, py


def cmd_check(schema_path: Path, ts_out: Path, py_out: Path) -> int:
    ts, py = generate(schema_path)
    drift = []
    for want, target in ((ts, ts_out), (py, py_out)):
        if not target.exists():
            drift.append(f"MISSING output: {target}")
        elif target.read_text(encoding="utf-8") != want:
            drift.append(f"DRIFT: {target} differs from regeneration")
    if drift:
        for d in drift:
            print(f"[generate_types] {d}", file=sys.stderr)
        print("[generate_types] --check FAIL: run the generator and commit the outputs", file=sys.stderr)
        return 1
    print(f"[generate_types] --check OK: {ts_out.name} + {py_out.name} byte-parity with {schema_path}")
    return 0


def self_test() -> int:
    """Hermetic fixtures — no repo state needed. Returns count of passed checks."""
    import tempfile

    def _obj(props, req=None, **extra):
        d = {"type": "object"}
        if req is not None:
            d["required"] = req
        d["properties"] = props
        d.update(extra)
        return d

    checks = 0
    ok_schema = {
        "openapi": "3.1.0",
        "components": {"schemas": {
            "Msg": _obj({"role": {"type": "string", "enum": ["system", "user", "assistant"]},
                         "content": {"type": "string"}}, req=["role", "content"]),
            "Req": _obj({"model": {"type": "string", "default": "auto"},
                         "messages": {"type": "array", "minItems": 1,
                                      "items": _obj({"role": {"type": "string"}}, req=["role"])},
                         "stream": {"type": "boolean", "default": False, "nullable": True}},
                        req=["messages"]),
            "Resp": _obj({"usage": _obj({"total_tokens": {"type": "integer"}})}),
        }},
    }
    with tempfile.TemporaryDirectory() as td:
        root = Path(td)
        good = root / "good.yaml"
        good.write_text(yaml.safe_dump(ok_schema, sort_keys=False), encoding="utf-8")

        # 1-2: clean schema generates deterministically
        ts1, py1 = generate(good)
        ts2, py2 = generate(good)
        checks += 1; assert ts1 == ts2 and py1 == py2, "determinism"
        # 3: required present in TS as mandatory field
        checks += 1; assert "  messages: Array<" in ts1 and "  model?:" in ts1, "TS required/optional"
        # 4: enum literal union
        checks += 1; assert '"system" | "user" | "assistant"' in ts1, "TS enum union"
        # 5: nullable union
        checks += 1; assert "| null" in ts1, "TS nullable"
        # 6: py required-split via inheritance (PEP 589: base required + total=False subclass)
        checks += 1; assert "class Req_Required(TypedDict):" in py1 and "class Req(Req_Required, total=False):" in py1, "py split"
        # 7: nested hoist naming (all-required item => Required base + total=False pass subclass)
        checks += 1; assert "class Req__messages__item_Required(TypedDict):" in py1 \
            and "class Req__messages__item(Req__messages__item_Required, total=False):" in py1, "py nested hoist"
        # 8: header present
        checks += 1; assert "DO NOT EDIT BY HAND" in ts1 and "DO NOT EDIT BY HAND" in py1, "generated header"

        # 9: the live main defect class — literal-string required — must abort
        bad = json.loads(json.dumps(ok_schema))
        bad["components"]["schemas"]["Req"]["required"] = "essages]"
        badf = root / "bad.yaml"
        badf.write_text(yaml.safe_dump(bad, sort_keys=False), encoding="utf-8")
        try:
            generate(badf)
            checks += 1; assert False, "typo schema must be rejected"
        except GenerateError as e:
            checks += 1; assert "must be an ARRAY" in str(e), f"fail-closed message: {e}"

        # 9b: raw-text lint catches the healed variant too (PyYAML-invisible defect)
        healed = yaml.safe_dump(ok_schema, sort_keys=False).replace(
            "required:\n- messages", "required: essages]")
        if "essages]" not in healed:  # dump style differs — splice by hand
            healed = yaml.safe_dump(ok_schema, sort_keys=False).replace(
                "- messages", "messages]").replace("required:", "required: es", 1)
        healedf = root / "healed.yaml"
        healedf.write_text(healed, encoding="utf-8")
        try:
            generate(healedf)
            checks += 1; assert False, "raw healed defect must be rejected"
        except GenerateError as e:
            checks += 1; assert "line " in str(e), f"raw lint line annotation: {e}"

        # 9c: operation-level required:true OUTSIDE components.schemas is legal
        op_ok = {"openapi": "3.1.0",
                 "paths": {"/x": {"post": {"requestBody": {"required": True}}}},
                 "components": {"schemas": {"A": _obj({"a": {"type": "string"}})}}}
        opf = root / "op.yaml"
        opf.write_text(yaml.safe_dump(op_ok, sort_keys=False), encoding="utf-8")
        generate(opf)
        checks += 1

        # 10: unknown type rejected
        bad2 = json.loads(json.dumps(ok_schema))
        bad2["components"]["schemas"]["Resp"]["properties"]["usage"]["type"] = "float64"
        f2 = root / "bad2.yaml"; f2.write_text(yaml.safe_dump(bad2, sort_keys=False), encoding="utf-8")
        try:
            generate(f2); checks += 1; assert False, "unknown type must be rejected"
        except GenerateError:
            checks += 1

        # 11: unresolvable $ref rejected
        bad3 = json.loads(json.dumps(ok_schema))
        bad3["components"]["schemas"]["Resp"]["properties"]["usage"] = {"$ref": "#/components/schemas/Nope"}
        f3 = root / "bad3.yaml"; f3.write_text(yaml.safe_dump(bad3, sort_keys=False), encoding="utf-8")
        try:
            generate(f3); checks += 1; assert False, "unresolvable $ref must be rejected"
        except GenerateError:
            checks += 1

        # 12-13: --check drift gate (ok → 0; corrupted output → 1)
        tsf = root / "types.ts"; pyf = root / "types.py"
        tsf.write_text(ts1, encoding="utf-8"); pyf.write_text(py1, encoding="utf-8")
        checks += 1; assert cmd_check(good, tsf, pyf) == 0, "check ok"
        tsf.write_text(ts1.replace("messages", "mesages"), encoding="utf-8")
        checks += 1; assert cmd_check(good, tsf, pyf) == 1, "check drift"

        # 14: missing output → drift (fail-closed, never silent-ok)
        tsf.unlink()
        checks += 1; assert cmd_check(good, tsf, pyf) == 1, "check missing"

    print(f"[generate_types] self-test: {checks}/{checks} checks passed")
    return checks


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description="Deterministic OpenAPI → TS+Python type generation (#375 Phase 4)")
    ap.add_argument("--schema", type=Path, help="path to the OpenAPI SSOT (api-schemas/gateway.openapi.yaml)")
    ap.add_argument("--ts-out", type=Path, help="TypeScript output path")
    ap.add_argument("--py-out", type=Path, help="Python output path")
    ap.add_argument("--check", action="store_true", help="byte-parity gate: regenerate and diff")
    ap.add_argument("--self-test", action="store_true", help="hermetic fixture suite")
    a = ap.parse_args(argv)
    try:
        if a.self_test:
            n = self_test()
            return 0 if n >= 15 else 2
        if not (a.schema and a.ts_out and a.py_out):
            ap.error("--schema, --ts-out and --py-out are required (or use --self-test)")
        if a.check:
            return cmd_check(a.schema, a.ts_out, a.py_out)
        ts, py = generate(a.schema)
        a.ts_out.parent.mkdir(parents=True, exist_ok=True)
        a.py_out.parent.mkdir(parents=True, exist_ok=True)
        a.ts_out.write_text(ts, encoding="utf-8")
        a.py_out.write_text(py, encoding="utf-8")
        print(f"[generate_types] wrote {a.ts_out} ({len(ts)}B) + {a.py_out} ({len(py)}B)")
        return 0
    except GenerateError as e:
        print(f"[generate_types] FAIL-CLOSED: {e}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    sys.exit(main())
